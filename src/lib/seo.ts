import type { Metadata } from "next";
import { siteUrl } from "@/lib/constants";
import type { Locale } from "@/lib/i18n";

/**
 * Single source of truth for public routes: CS slug (filesystem) and the EN
 * slug that appears in /en/... URLs (mapped back to CS slugs in src/proxy.ts).
 * Used by the sitemap and by every page's canonical / hreflang / og:url.
 */
export const routes = {
  home: { cs: "", en: "", changeFrequency: "weekly", priority: 1 },
  pricing: { cs: "/cenik", en: "/pricing", changeFrequency: "monthly", priority: 0.8 },
  reportTypes: { cs: "/typy-zprav", en: "/report-types", changeFrequency: "monthly", priority: 0.7 },
  security: { cs: "/bezpecnost", en: "/security", changeFrequency: "monthly", priority: 0.7 },
  contact: { cs: "/kontakt", en: "/contact", changeFrequency: "monthly", priority: 0.7 },
  faq: { cs: "/faq", en: "/faq", changeFrequency: "monthly", priority: 0.6 },
  demo: { cs: "/demo", en: "/demo", changeFrequency: "monthly", priority: 0.6 },
  terms: { cs: "/podminky", en: "/terms", changeFrequency: "yearly", priority: 0.3 },
  privacy: { cs: "/ochrana-soukromi", en: "/privacy", changeFrequency: "yearly", priority: 0.3 },
} as const;

export type RouteKey = keyof typeof routes;

export function routeUrl(key: RouteKey, lang: Locale): string {
  const r = routes[key];
  return lang === "cs" ? `${siteUrl}${r.cs}` : `${siteUrl}/en${r.en}`;
}

export function routeLanguages(key: RouteKey) {
  return {
    cs: routeUrl(key, "cs"),
    en: routeUrl(key, "en"),
    "x-default": routeUrl(key, "cs"),
  };
}

/**
 * Per-page metadata. Next.js replaces (not merges) `openGraph` and `twitter`
 * objects from parent layouts, so the full objects are rebuilt here. The OG
 * image is generated by the opengraph-image route in [lang]/.
 */
export function pageMetadata(
  key: RouteKey,
  lang: Locale,
  title: string,
  description: string,
): Metadata {
  const url = routeUrl(key, lang);
  const image = { url: `${siteUrl}/${lang}/opengraph-image`, width: 1200, height: 630, alt: title };
  return {
    title,
    description,
    alternates: { canonical: url, languages: routeLanguages(key) },
    openGraph: {
      title,
      description,
      url,
      siteName: "ANOTE",
      locale: lang === "cs" ? "cs_CZ" : "en_US",
      type: "website",
      images: [image],
    },
    twitter: { card: "summary_large_image", title, description, images: [image.url] },
  };
}

/**
 * Czech-only content pages (/obory/*, /clanky/*). They have no English
 * counterpart, so there is no `en` alternate: canonical is the page itself and
 * hreflang lists only `cs` + `x-default`.
 */
export function contentUrl(path: string): string {
  return `${siteUrl}${path}`;
}

export function contentMetadata({
  path,
  title,
  description,
  type = "website",
  publishedTime,
  modifiedTime,
}: {
  path: string;
  title: string;
  description: string;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
}): Metadata {
  const url = contentUrl(path);
  const image = { url: `${siteUrl}/cs/opengraph-image`, width: 1200, height: 630, alt: title };
  return {
    title,
    description,
    alternates: { canonical: url, languages: { cs: url, "x-default": url } },
    openGraph: {
      title,
      description,
      url,
      siteName: "ANOTE",
      locale: "cs_CZ",
      images: [image],
      ...(type === "article"
        ? { type: "article", publishedTime, modifiedTime, authors: ["ANOTE"] }
        : { type: "website" }),
    },
    twitter: { card: "summary_large_image", title, description, images: [image.url] },
  };
}
